export function getItemField(item, fieldPrefix, lang) {
  if (!item) return '';
  const langKey = `${fieldPrefix}_${lang}`;
  if (item[langKey]) return item[langKey];
  // Fallback to English
  const enKey = `${fieldPrefix}_en`;
  if (item[enKey]) return item[enKey];
  return item[fieldPrefix] || '';
}
